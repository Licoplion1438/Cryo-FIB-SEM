def tensor_to_preview(
    tensor,
):
    """Convert a model tensor to a uint8 display image."""
    image = (
        tensor.detach()
        .float()
        .cpu()[0, 0]
        .numpy()
    )

    image = np.clip(
        image,
        0.0,
        1.0,
    )

    image = np.round(
        image * 255.0
    ).astype(np.uint8)

    return cv2.resize(
        image,
        (
            PREVIEW_SIZE,
            PREVIEW_SIZE,
        ),
        interpolation=cv2.INTER_AREA,
    )


def add_title(
    image,
    title,
):
    """Append a small title bar above a grayscale image."""
    header = np.full(
        (
            28,
            image.shape[1],
        ),
        255,
        dtype=np.uint8,
    )

    cv2.putText(
        header,
        title,
        (
            8,
            19,
        ),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.48,
        0,
        1,
        cv2.LINE_AA,
    )

    return np.concatenate(
        [
            header,
            image,
        ],
        axis=0,
    )


def select_preview_indices(
    dataset,
):
    """Select a fixed count of degraded and identity validation samples."""
    selected_indices = []

    preview_counts = {
        "degraded":
            NUM_PREVIEW_DEGRADED,
        "clean_identity":
            NUM_PREVIEW_CLEAN_IDENTITY,
    }

    for (
        wanted_type,
        wanted_count,
    ) in preview_counts.items():
        matching = [
            i
            for i, row
            in enumerate(
                dataset.rows
            )
            if row.get(
                "sample_type",
                "degraded",
            ) == wanted_type
        ]

        selected_indices.extend(
            matching[
                :wanted_count
            ]
        )

    if len(
        selected_indices
    ) < min(
        NUM_PREVIEW_IMAGES,
        len(dataset),
    ):
        selected_set = set(
            selected_indices
        )

        selected_indices.extend(
            i
            for i
            in range(
                len(dataset)
            )
            if i
            not in selected_set
        )

    return selected_indices[
        :min(
            NUM_PREVIEW_IMAGES,
            len(dataset),
        )
    ]


