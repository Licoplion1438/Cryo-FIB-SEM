def compute_psnr(pred, target):
    """Compute clipped reconstruction PSNR."""
    pred = torch.clamp(pred, 0.0, 1.0)
    mse = F.mse_loss(pred, target).item()
    if mse <= 1e-12:
        return 99.0
    return 10.0 * math.log10(1.0 / mse)


def run_epoch(
    model,
    loader,
    device,
    optimizer=None,
    scaler=None,
):
    """
    Native-1024 training or validation epoch.

    Scientific update semantics:
    - one 1024x1024 sample per microbatch
    - same forward model
    - same three loss terms
    - same loss scaling by GRAD_ACCUM_STEPS
    - optimizer.step() after every 4 training microbatches
    - same metric computation and type-specific validation statistics

    Required geometry change:
    - there is no 2048 -> four 1024 patch split anymore.
    """
    training = (
        optimizer is not None
    )

    if training:
        model.train()
        optimizer.zero_grad(
            set_to_none=True
        )
    else:
        model.eval()

    loss_sum = 0.0
    weighted_l1_sum = 0.0
    transition_grad_l1_sum = 0.0
    transition_term_sum = 0.0
    transition_fraction_sum = 0.0
    shallow_regional_l1_sum = 0.0
    shallow_regional_term_sum = 0.0
    shallow_regional_fraction_sum = 0.0

    shallow_scale_loss_sums = {
        int(
            round(
                sigma
            )
        ): 0.0
        for sigma
        in SHALLOW_REGIONAL_SIGMAS
    }

    shallow_scale_fraction_sums = {
        int(
            round(
                sigma
            )
        ): 0.0
        for sigma
        in SHALLOW_REGIONAL_SIGMAS
    }

    psnr_sum = 0.0
    count = 0

    type_stats = {
        "degraded": {
            "loss_sum": 0.0,
            "psnr_sum": 0.0,
            "count": 0,
        },
        "clean_identity": {
            "loss_sum": 0.0,
            "psnr_sum": 0.0,
            "count": 0,
        },
    }

    context = (
        nullcontext()
        if training
        else torch.no_grad()
    )

    accum_counter = 0

    def optimizer_step_if_needed():
        """Unscale, clip, update optimizer, and clear accumulated gradients."""
        nonlocal accum_counter

        if not training:
            return

        if accum_counter <= 0:
            return

        scaler.unscale_(
            optimizer
        )

        nn.utils.clip_grad_norm_(
            model.parameters(),
            GRAD_CLIP_NORM,
        )

        scaler.step(
            optimizer
        )

        scaler.update()

        optimizer.zero_grad(
            set_to_none=True
        )

        accum_counter = 0

    with context:
        pbar = tqdm(
            loader,
            desc=(
                "Train"
                if training
                else "Val"
            ),
            leave=False,
        )

        for sample_batch in pbar:
            noisy = (
                sample_batch[
                    "input"
                ]
                .to(
                    device,
                    non_blocking=True,
                )
            )

            target = (
                sample_batch[
                    "target"
                ]
                .to(
                    device,
                    non_blocking=True,
                )
            )

            transition_mask = (
                sample_batch[
                    "transition_mask"
                ]
                .to(
                    device,
                    non_blocking=True,
                )
            )

            current_types = list(
                sample_batch[
                    "sample_type"
                ]
            )

            if noisy.shape[0] != BATCH_SIZE:
                raise RuntimeError(
                    f"Expected microbatch size {BATCH_SIZE}, "
                    f"got {noisy.shape[0]}"
                )

            if noisy.shape[-2:] != (
                IMAGE_SIZE,
                IMAGE_SIZE,
            ):
                raise RuntimeError(
                    "Expected native "
                    f"{IMAGE_SIZE}x{IMAGE_SIZE} input, "
                    f"got {tuple(noisy.shape)}"
                )

            with amp_context(
                device
            ):
                pred = model(
                    noisy
                )

                if not torch.isfinite(
                    pred
                ).all():
                    raise RuntimeError(
                        "NaN/Inf in prediction."
                    )

                loss_terms = compute_loss_terms(
                    pred,
                    target,
                    noisy,
                    transition_mask,
                )

                loss = loss_terms[
                    "total"
                ]

            if not torch.isfinite(
                loss
            ):
                raise RuntimeError(
                    "NaN/Inf in loss."
                )

            if training:
                # Preserve the original effective accumulation regime:
                # four 1024 microbatches -> one optimizer update.
                scaled_loss = (
                    loss
                    / float(
                        GRAD_ACCUM_STEPS
                    )
                )

                scaler.scale(
                    scaled_loss
                ).backward()

                accum_counter += 1

                if (
                    accum_counter
                    >= GRAD_ACCUM_STEPS
                ):
                    optimizer_step_if_needed()

            sample_batch_size = (
                noisy.shape[0]
            )

            loss_value = float(
                loss.detach().cpu()
            )

            weighted_l1_value = float(
                loss_terms[
                    "weighted_l1"
                ].detach().cpu()
            )

            transition_grad_l1_value = float(
                loss_terms[
                    "transition_grad_l1"
                ].detach().cpu()
            )

            transition_term_value = float(
                loss_terms[
                    "transition_term"
                ].detach().cpu()
            )

            transition_fraction_value = float(
                loss_terms[
                    "transition_fraction"
                ].detach().cpu()
            )

            shallow_regional_l1_value = float(
                loss_terms[
                    "shallow_regional_l1"
                ].detach().cpu()
            )

            shallow_regional_term_value = float(
                loss_terms[
                    "shallow_regional_term"
                ].detach().cpu()
            )

            shallow_regional_fraction_value = float(
                loss_terms[
                    "shallow_regional_fraction"
                ].detach().cpu()
            )

            psnr_value = compute_psnr(
                pred.detach(),
                target,
            )

            loss_sum += (
                loss_value
                * sample_batch_size
            )

            weighted_l1_sum += (
                weighted_l1_value
                * sample_batch_size
            )

            transition_grad_l1_sum += (
                transition_grad_l1_value
                * sample_batch_size
            )

            transition_term_sum += (
                transition_term_value
                * sample_batch_size
            )

            transition_fraction_sum += (
                transition_fraction_value
                * sample_batch_size
            )

            shallow_regional_l1_sum += (
                shallow_regional_l1_value
                * sample_batch_size
            )

            shallow_regional_term_sum += (
                shallow_regional_term_value
                * sample_batch_size
            )

            shallow_regional_fraction_sum += (
                shallow_regional_fraction_value
                * sample_batch_size
            )

            for sigma in SHALLOW_REGIONAL_SIGMAS:
                key = int(
                    round(
                        sigma
                    )
                )

                shallow_scale_loss_sums[
                    key
                ] += (
                    float(
                        loss_terms[
                            f"shallow_regional_l1_sigma{key}"
                        ].detach().cpu()
                    )
                    * sample_batch_size
                )

                shallow_scale_fraction_sums[
                    key
                ] += (
                    float(
                        loss_terms[
                            f"shallow_regional_fraction_sigma{key}"
                        ].detach().cpu()
                    )
                    * sample_batch_size
                )

            psnr_sum += (
                psnr_value
                * sample_batch_size
            )

            count += sample_batch_size

            # Reuse the already-computed main loss / PSNR for type statistics.
            # BATCH_SIZE is fixed at 1, so this is exactly the same per-sample
            # statistic without a second logging-only compute_loss() pass.
            sample_type = current_types[0]
            if sample_type not in type_stats:
                raise RuntimeError(
                    f"Unexpected sample_type: {sample_type}"
                )

            type_stats[
                sample_type
            ][
                "loss_sum"
            ] += loss_value

            type_stats[
                sample_type
            ][
                "psnr_sum"
            ] += psnr_value

            type_stats[
                sample_type
            ][
                "count"
            ] += 1

            pbar.set_postfix(
                total=(
                    f"{loss_sum / count:.4f}"
                ),
                pixel=(
                    f"{weighted_l1_sum / count:.4f}"
                ),
                trans=(
                    f"{transition_term_sum / count:.4f}"
                ),
                regional=(
                    f"{shallow_regional_term_sum / count:.4f}"
                ),
                psnr=(
                    f"{psnr_sum / count:.2f}"
                ),
            )

    # Defensive final step if a future dataset/batch change makes the number
    # of training microbatches not divisible by GRAD_ACCUM_STEPS.
    if (
        training
        and accum_counter > 0
    ):
        optimizer_step_if_needed()

    if count == 0:
        raise RuntimeError(
            "Empty dataloader."
        )

    metrics = {
        "loss":
            loss_sum / count,
        "weighted_l1":
            weighted_l1_sum / count,
        "transition_grad_l1":
            transition_grad_l1_sum / count,
        "transition_term":
            transition_term_sum / count,
        "transition_fraction":
            transition_fraction_sum / count,
        "shallow_regional_l1":
            shallow_regional_l1_sum / count,
        "shallow_regional_term":
            shallow_regional_term_sum / count,
        "shallow_regional_fraction":
            shallow_regional_fraction_sum / count,
        "psnr":
            psnr_sum / count,
    }

    for sigma in SHALLOW_REGIONAL_SIGMAS:
        key = int(
            round(
                sigma
            )
        )

        metrics[
            f"shallow_regional_l1_sigma{key}"
        ] = (
            shallow_scale_loss_sums[
                key
            ]
            / count
        )

        metrics[
            f"shallow_regional_fraction_sigma{key}"
        ] = (
            shallow_scale_fraction_sums[
                key
            ]
            / count
        )

    for sample_type, prefix in (
        (
            "degraded",
            "degraded",
        ),
        (
            "clean_identity",
            "clean_identity",
        ),
    ):
        stats = type_stats[
            sample_type
        ]

        metrics[
            f"{prefix}_count"
        ] = stats[
            "count"
        ]

        metrics[
            f"{prefix}_loss"
        ] = (
            stats[
                "loss_sum"
            ]
            / stats[
                "count"
            ]
            if stats[
                "count"
            ]
            else float(
                "nan"
            )
        )

        metrics[
            f"{prefix}_psnr"
        ] = (
            stats[
                "psnr_sum"
            ]
            / stats[
                "count"
            ]
            if stats[
                "count"
            ]
            else float(
                "nan"
            )
        )

    return metrics


