def collect_rows(split):
    """Read the requested split from the synthesis metadata CSV."""
    rows = []

    with open(
        METADATA_PATH,
        "r",
        newline="",
    ) as f:
        for row in csv.DictReader(f):
            if row["split"] == split:
                rows.append(row)

    rows.sort(
        key=lambda r: int(
            r["sample_id"]
        )
    )

    if not rows:
        raise RuntimeError(
            f"No samples found for split='{split}'."
        )

    return rows


def build_transition_maps_numpy(
    input_image01,
    target01,
):
    """
    Build the correction sign-transition band on the COMPLETE native
    1024x1024 sample.

    input_image01 / target01:
        float32 in [0,1]
    """
    gt_correction = (
        target01.astype(np.float32)
        - input_image01.astype(np.float32)
    )

    positive_mask = (
        gt_correction
        >= TRANSITION_CORRECTION_THRESHOLD
    ).astype(np.uint8)

    negative_mask = (
        gt_correction
        <= -TRANSITION_CORRECTION_THRESHOLD
    ).astype(np.uint8)

    kernel_size = (
        2 * TRANSITION_RADIUS
        + 1
    )

    kernel = cv2.getStructuringElement(
        cv2.MORPH_ELLIPSE,
        (
            kernel_size,
            kernel_size,
        ),
    )

    positive_near = cv2.dilate(
        positive_mask,
        kernel,
        iterations=1,
    )

    negative_near = cv2.dilate(
        negative_mask,
        kernel,
        iterations=1,
    )

    transition_mask = (
        (positive_near > 0)
        & (negative_near > 0)
    ).astype(np.float32)

    return {
        "gt_correction":
            gt_correction.astype(np.float32),
        "positive_mask":
            positive_mask.astype(np.float32),
        "negative_mask":
            negative_mask.astype(np.float32),
        "transition_mask":
            transition_mask,
    }


def transition_cache_signature(rows):
    """Fingerprint source pairs plus the exact transition-mask definition."""
    digest = hashlib.sha256()
    digest.update(
        (
            f"image_size={IMAGE_SIZE}|"
            f"threshold={TRANSITION_CORRECTION_THRESHOLD:.17g}|"
            f"radius={TRANSITION_RADIUS}"
        ).encode("utf-8")
    )

    for row in rows:
        digest.update(str(row.get("sample_id", "")).encode("utf-8"))
        digest.update(str(row.get("output_name", "")).encode("utf-8"))

        for key in ("noisy_relpath", "clean_relpath"):
            relpath = row.get(key, "")
            if not relpath:
                raise KeyError(
                    f"Synthesis metadata row is missing {key}: "
                    f"{row.get('output_name', '<unknown>')}"
                )

            path = DATA_ROOT / relpath
            if not path.exists():
                raise FileNotFoundError(path)

            stat = path.stat()
            digest.update(relpath.encode("utf-8"))
            digest.update(str(stat.st_size).encode("utf-8"))
            digest.update(str(stat.st_mtime_ns).encode("utf-8"))

    return digest.hexdigest()


def ensure_transition_cache(rows, split):
    """
    Build deterministic GT transition masks once and store them as uint8.

    The cache contains only binary {0,1} masks. Dataset loading casts each
    mask back to float32 before the unchanged training loss sees it.
    """
    ensure_dir(TRANSITION_CACHE_DIR)

    cache_path = (
        TRANSITION_CACHE_DIR
        / f"{split}_transition_masks_uint8.npy"
    )
    manifest_path = (
        TRANSITION_CACHE_DIR
        / f"{split}_transition_masks_manifest.json"
    )

    signature = transition_cache_signature(rows)
    expected_shape = (
        len(rows),
        IMAGE_SIZE,
        IMAGE_SIZE,
    )

    if cache_path.exists() and manifest_path.exists():
        try:
            manifest = json.loads(
                manifest_path.read_text(encoding="utf-8")
            )
            cached = np.load(
                cache_path,
                mmap_mode="r",
            )
            valid = (
                manifest.get("signature") == signature
                and tuple(cached.shape) == expected_shape
                and cached.dtype == np.uint8
            )
            del cached
            if valid:
                print(
                    f"Transition cache [{split}]: reuse {cache_path}"
                )
                return cache_path
        except Exception:
            pass

    print(
        f"Transition cache [{split}]: building {len(rows)} masks once..."
    )

    tmp_path = cache_path.with_name(
        cache_path.name + ".tmp"
    )
    if tmp_path.exists():
        tmp_path.unlink()

    cache = np.lib.format.open_memmap(
        tmp_path,
        mode="w+",
        dtype=np.uint8,
        shape=expected_shape,
    )

    try:
        for index, row in enumerate(
            tqdm(
                rows,
                desc=f"Transition cache [{split}]",
                leave=False,
            )
        ):
            name = row["output_name"]
            noisy_path = DATA_ROOT / row["noisy_relpath"]
            clean_path = DATA_ROOT / row["clean_relpath"]

            noisy = (
                read_uint8_tif(noisy_path).astype(np.float32)
                / 255.0
            )
            clean = (
                read_uint8_tif(clean_path).astype(np.float32)
                / 255.0
            )

            transition_mask = build_transition_maps_numpy(
                noisy,
                clean,
            )["transition_mask"]

            if transition_mask.shape != (
                IMAGE_SIZE,
                IMAGE_SIZE,
            ):
                raise RuntimeError(
                    f"Unexpected transition-mask shape for {name}: "
                    f"{transition_mask.shape}"
                )

            cache[index] = transition_mask.astype(
                np.uint8,
                copy=False,
            )

        cache.flush()
    finally:
        del cache

    tmp_path.replace(cache_path)

    manifest = {
        "split": split,
        "count": len(rows),
        "shape": list(expected_shape),
        "dtype": "uint8",
        "signature": signature,
        "transition_correction_threshold": TRANSITION_CORRECTION_THRESHOLD,
        "transition_radius_px": TRANSITION_RADIUS,
    }
    manifest_path.write_text(
        json.dumps(manifest, indent=2) + "\n",
        encoding="utf-8",
    )

    print(
        f"Transition cache [{split}]: saved {cache_path}"
    )
    return cache_path


class WholeSliceDataset(Dataset):
    def __init__(
        self,
        rows,
        transition_cache_path,
        data_root=None,
    ):
        """Keep paired rows, worker-safe dataset root, and cached mask path."""
        self.rows = list(rows)
        self.data_root = Path(DATA_ROOT if data_root is None else data_root)
        self.transition_cache_path = Path(
            transition_cache_path
        )
        self._transition_cache = None

    def __getstate__(self):
        """Clear the memory mapping before DataLoader worker pickling."""
        state = self.__dict__.copy()
        state["_transition_cache"] = None
        return state

    def _get_transition_cache(self):
        """Lazily map binary transition masks in the current worker."""
        if self._transition_cache is None:
            self._transition_cache = np.load(
                self.transition_cache_path,
                mmap_mode="r",
            )
        return self._transition_cache

    def __len__(self):
        """Return the number of paired native-size samples."""
        return len(
            self.rows
        )

    def __getitem__(
        self,
        index,
    ):
        """Load one paired TIFF and its precomputed transition mask."""
        row = self.rows[index]
        name = row["output_name"]

        noisy_relpath = row.get(
            "noisy_relpath",
            "",
        )
        clean_relpath = row.get(
            "clean_relpath",
            "",
        )

        if not noisy_relpath or not clean_relpath:
            raise KeyError(
                f"Synthesis metadata row is missing clean_relpath/noisy_relpath: {name}"
            )

        noisy_path = self.data_root / noisy_relpath
        clean_path = self.data_root / clean_relpath

        if (
            not noisy_path.exists()
            or not clean_path.exists()
        ):
            raise FileNotFoundError(
                f"Missing pair: {name}"
            )

        noisy = (
            read_uint8_tif(
                noisy_path
            ).astype(np.float32)
            / 255.0
        )

        clean = (
            read_uint8_tif(
                clean_path
            ).astype(np.float32)
            / 255.0
        )

        # Deterministic GT transition mask was built once before training and
        # stored as uint8 {0,1}. Cast back to float32 so the unchanged training loss
        # receives the same mask dtype/range as in the original implementation.
        transition_mask = np.array(
            self._get_transition_cache()[index],
            dtype=np.float32,
            copy=True,
        )

        return {
            "input":
                torch.from_numpy(
                    noisy
                ).unsqueeze(0),
            "target":
                torch.from_numpy(
                    clean
                ).unsqueeze(0),
            "transition_mask":
                torch.from_numpy(
                    transition_mask
                ).unsqueeze(0),
            "name":
                name,
            "sample_type":
                row.get(
                    "sample_type",
                    "degraded",
                ),
        }


