def gaussian_blur_map(
    image,
    sigma,
):
    """Apply separable Gaussian convolution with reflection padding."""
    radius = max(
        1,
        int(
            round(
                3.0 * sigma
            )
        ),
    )

    coords = torch.arange(
        -radius,
        radius + 1,
        device=image.device,
        dtype=image.dtype,
    )

    kernel = torch.exp(
        -(coords ** 2)
        / (
            2.0
            * sigma
            * sigma
        )
    )

    kernel = (
        kernel
        / kernel.sum()
    )

    pad = radius

    x = F.pad(
        image,
        (
            pad,
            pad,
            0,
            0,
        ),
        mode="reflect",
    )

    x = F.conv2d(
        x,
        kernel.view(
            1,
            1,
            1,
            -1,
        ),
    )

    x = F.pad(
        x,
        (
            0,
            0,
            pad,
            pad,
        ),
        mode="reflect",
    )

    x = F.conv2d(
        x,
        kernel.view(
            1,
            1,
            -1,
            1,
        ),
    )

    return x


def build_loss_weight(
    input_image,
    target,
):
    """
    Exact preserved-best synthetic weighting.
    """
    with torch.no_grad():
        diff = torch.abs(
            input_image - target
        )

        importance = torch.clamp(
            (
                diff
                - WEIGHT_DIFF_LOW
            )
            / (
                WEIGHT_DIFF_HIGH
                - WEIGHT_DIFF_LOW
            ),
            0.0,
            1.0,
        )

        importance = gaussian_blur_map(
            importance,
            WEIGHT_BLUR_SIGMA,
        )

        weight = (
            1.0
            + WEIGHT_EXTRA
            * importance
        )

    return weight


def compute_loss_terms(
    pred,
    target,
    input_image,
    transition_mask,
):
    """
    Training loss:

        preserved-best weighted pixel L1
        + transition-local SIGNED correction-gradient L1
        + shallow multi-scale REGIONAL correction-field L1

    The new regional term is deliberately sign-symmetric:
    shallow bright and shallow dark background offsets are both supervised.

    gt_correction   = target - input
    pred_correction = pred   - input
    """
    weight = build_loss_weight(
        input_image,
        target,
    )

    pixel_error = torch.abs(
        pred - target
    )

    weighted_l1 = (
        torch.sum(
            weight
            * pixel_error
        )
        / torch.sum(
            weight
        )
    )

    gt_correction = (
        target
        - input_image
    )

    pred_correction = (
        pred
        - input_image
    )

    # --------------------------------------------------------
    # Transition-local signed correction gradient term
    # --------------------------------------------------------
    pred_dx = (
        pred_correction[
            :,
            :,
            :,
            1:
        ]
        - pred_correction[
            :,
            :,
            :,
            :-1
        ]
    )

    gt_dx = (
        gt_correction[
            :,
            :,
            :,
            1:
        ]
        - gt_correction[
            :,
            :,
            :,
            :-1
        ]
    )

    pred_dy = (
        pred_correction[
            :,
            :,
            1:,
            :
        ]
        - pred_correction[
            :,
            :,
            :-1,
            :
        ]
    )

    gt_dy = (
        gt_correction[
            :,
            :,
            1:,
            :
        ]
        - gt_correction[
            :,
            :,
            :-1,
            :
        ]
    )

    grad_error_x = torch.abs(
        pred_dx
        - gt_dx
    )

    grad_error_y = torch.abs(
        pred_dy
        - gt_dy
    )

    transition_weight_x = torch.maximum(
        transition_mask[
            :,
            :,
            :,
            1:
        ],
        transition_mask[
            :,
            :,
            :,
            :-1
        ],
    )

    transition_weight_y = torch.maximum(
        transition_mask[
            :,
            :,
            1:,
            :
        ],
        transition_mask[
            :,
            :,
            :-1,
            :
        ],
    )

    transition_edge_count = (
        torch.sum(
            transition_weight_x
        )
        + torch.sum(
            transition_weight_y
        )
    )

    transition_grad_l1 = (
        torch.sum(
            transition_weight_x
            * grad_error_x
        )
        + torch.sum(
            transition_weight_y
            * grad_error_y
        )
    ) / torch.clamp(
        transition_edge_count,
        min=1.0,
    )

    transition_term = (
        TRANSITION_LOSS_WEIGHT
        * transition_grad_l1
    )

    # --------------------------------------------------------
    # Shallow regional correction-field term
    # --------------------------------------------------------
    #
    # We first look at the LOW-FREQUENCY GT correction itself.
    # A location participates when:
    #
    #     1/255 <= |Gaussian(C_gt)| <= 8/255
    #
    # and its raw GT correction is not a strong >=20-gray artefact center.
    #
    # This directly targets the shallow regional correction regime
    # diagnostic, rather than lowering the global weighted-L1 threshold.
    raw_gt_abs = torch.abs(
        gt_correction
    )

    regional_loss_sum = pred.new_tensor(
        0.0
    )

    regional_fraction_sum = pred.new_tensor(
        0.0
    )

    regional_scale_count = 0

    regional_scale_losses = {}
    regional_scale_fractions = {}

    for sigma in SHALLOW_REGIONAL_SIGMAS:
        pred_regional = gaussian_blur_map(
            pred_correction,
            sigma,
        )

        with torch.no_grad():
            gt_regional = gaussian_blur_map(
                gt_correction,
                sigma,
            )

            gt_regional_abs = torch.abs(
                gt_regional
            )

            regional_mask = (
                (
                    gt_regional_abs
                    >= SHALLOW_REGIONAL_MIN
                )
                & (
                    gt_regional_abs
                    <= SHALLOW_REGIONAL_MAX
                )
                & (
                    raw_gt_abs
                    < SHALLOW_REGIONAL_RAW_STRONG_EXCLUDE
                )
            ).to(
                dtype=pred.dtype
            )

        regional_error = torch.abs(
            pred_regional
            - gt_regional
        )

        regional_count = torch.sum(
            regional_mask
        )

        scale_loss = (
            torch.sum(
                regional_mask
                * regional_error
            )
            / torch.clamp(
                regional_count,
                min=1.0,
            )
        )

        scale_fraction = regional_mask.mean()

        regional_loss_sum = (
            regional_loss_sum
            + scale_loss
        )

        regional_fraction_sum = (
            regional_fraction_sum
            + scale_fraction
        )

        regional_scale_count += 1

        key = int(
            round(
                float(
                    sigma
                )
            )
        )

        regional_scale_losses[
            key
        ] = scale_loss

        regional_scale_fractions[
            key
        ] = scale_fraction

    shallow_regional_l1 = (
        regional_loss_sum
        / max(
            regional_scale_count,
            1,
        )
    )

    shallow_regional_fraction = (
        regional_fraction_sum
        / max(
            regional_scale_count,
            1,
        )
    )

    shallow_regional_term = (
        SHALLOW_REGIONAL_LOSS_WEIGHT
        * shallow_regional_l1
    )

    total = (
        weighted_l1
        + transition_term
        + shallow_regional_term
    )

    result = {
        "total":
            total,
        "weighted_l1":
            weighted_l1,
        "transition_grad_l1":
            transition_grad_l1,
        "transition_term":
            transition_term,
        "transition_fraction":
            transition_mask.mean(),
        "transition_edge_count":
            transition_edge_count,
        "shallow_regional_l1":
            shallow_regional_l1,
        "shallow_regional_term":
            shallow_regional_term,
        "shallow_regional_fraction":
            shallow_regional_fraction,
        "weight_map":
            weight,
        "pixel_error":
            pixel_error,
        "gt_correction":
            gt_correction,
        "pred_correction":
            pred_correction,
        "pred_dx":
            pred_dx,
        "pred_dy":
            pred_dy,
        "gt_dx":
            gt_dx,
        "gt_dy":
            gt_dy,
        "grad_error_x":
            grad_error_x,
        "grad_error_y":
            grad_error_y,
        "transition_weight_x":
            transition_weight_x,
        "transition_weight_y":
            transition_weight_y,
    }

    for key, value in regional_scale_losses.items():
        result[
            f"shallow_regional_l1_sigma{key}"
        ] = value

    for key, value in regional_scale_fractions.items():
        result[
            f"shallow_regional_fraction_sigma{key}"
        ] = value

    return result


