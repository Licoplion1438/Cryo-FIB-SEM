def save_checkpoint(path, model, optimizer, scheduler, scaler, epoch,
                    best_val_loss, best_meaningful_val, meaningful_bad_epochs,
                    lr_reductions):
    """Save original-format model, optimizer, scheduler, and scaler states."""
    torch.save({
        "epoch": epoch,
        "model_state_dict": model.state_dict(),
        "optimizer_state_dict": optimizer.state_dict(),
        "scheduler_state_dict": scheduler.state_dict(),
        "scaler_state_dict": scaler.state_dict() if scaler is not None else None,
        "best_val_loss": best_val_loss,
        "best_meaningful_val": best_meaningful_val,
        "meaningful_bad_epochs": meaningful_bad_epochs,
        "lr_reductions": lr_reductions,
    }, path)


def load_checkpoint(path, model, optimizer, scheduler, scaler, device):
    """Restore the original checkpoint state for training resumption."""
    ckpt = torch.load(path, map_location=device)
    model.load_state_dict(ckpt["model_state_dict"])
    optimizer.load_state_dict(ckpt["optimizer_state_dict"])
    scheduler.load_state_dict(ckpt["scheduler_state_dict"])
    if scaler is not None and ckpt.get("scaler_state_dict") is not None:
        scaler.load_state_dict(ckpt["scaler_state_dict"])

    return {
        "start_epoch": int(ckpt["epoch"]) + 1,
        "best_val_loss": float(ckpt.get("best_val_loss", float("inf"))),
        "best_meaningful_val": float(ckpt.get("best_meaningful_val", float("inf"))),
        "meaningful_bad_epochs": int(ckpt.get("meaningful_bad_epochs", 0)),
        "lr_reductions": int(ckpt.get("lr_reductions", 0)),
    }


