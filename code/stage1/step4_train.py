def configure_run(args):
    """Bind CLI paths in the parent process without changing training math."""
    global DATA_ROOT, METADATA_PATH, OUTPUT_ROOT, TRANSITION_CACHE_DIR
    global CHECKPOINT_DIR, PREVIEW_DIR, BEST_CKPT, LAST_CKPT
    global HISTORY_CSV, LOSS_PLOT, LR_PLOT, CONFIG_JSON
    global EXPERIMENT_DESCRIPTION, TRAINING_REPORT
    global NUM_WORKERS, PERSISTENT_WORKERS, NUM_EPOCHS
    global LEARNING_RATE, WEIGHT_DECAY, RESUME_TRAINING, OVERWRITE_OUTPUT

    if args.workers < 0:
        raise ValueError("--workers must be >= 0.")
    if args.epochs < 1:
        raise ValueError("--epochs must be >= 1.")
    if not math.isfinite(args.learning_rate) or args.learning_rate <= 0:
        raise ValueError("--learning-rate must be finite and positive.")
    if not math.isfinite(args.weight_decay) or args.weight_decay < 0:
        raise ValueError("--weight-decay must be finite and non-negative.")
    if args.resume and args.overwrite:
        raise ValueError("--resume and --overwrite cannot be used together.")

    data_root = args.data_root.expanduser().resolve()
    output_root = args.output_root.expanduser().resolve()
    metadata_path = (
        args.metadata_path.expanduser().resolve()
        if args.metadata_path is not None
        else data_root / "metadata.csv"
    )
    # Protect all input images from accidental output-tree deletion, including
    # configurations where output-root is a parent or child of data-root.
    if (data_root == output_root or data_root in output_root.parents
            or output_root in data_root.parents):
        raise ValueError("Input and training output roots must be separate, non-nested directories.")
    if not data_root.is_dir():
        raise FileNotFoundError(f"Synthetic dataset root not found: {data_root}")
    if not metadata_path.is_file():
        raise FileNotFoundError(f"Synthesis metadata not found: {metadata_path}")

    DATA_ROOT = data_root
    METADATA_PATH = metadata_path
    OUTPUT_ROOT = output_root
    TRANSITION_CACHE_DIR = output_root / "transition_cache"
    CHECKPOINT_DIR = output_root / "checkpoints"
    PREVIEW_DIR = output_root / "visualization" / "previews"
    BEST_CKPT = CHECKPOINT_DIR / "best.pt"
    LAST_CKPT = CHECKPOINT_DIR / "last.pt"
    HISTORY_CSV = output_root / "train_log.csv"
    LOSS_PLOT = output_root / "loss_curve.png"
    LR_PLOT = output_root / "lr_curve.png"
    CONFIG_JSON = output_root / "config.json"
    EXPERIMENT_DESCRIPTION = output_root / "experiment_description.txt"
    TRAINING_REPORT = output_root / "training_report.txt"

    NUM_WORKERS = args.workers
    PERSISTENT_WORKERS = args.workers > 0
    NUM_EPOCHS = args.epochs
    LEARNING_RATE = args.learning_rate
    WEIGHT_DECAY = args.weight_decay
    RESUME_TRAINING = args.resume
    OVERWRITE_OUTPUT = args.overwrite


