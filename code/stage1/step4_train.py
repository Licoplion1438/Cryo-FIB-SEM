def read_uint8_tif(path):
    """Read and validate one native-size grayscale uint8 TIFF."""
    image = tifffile.imread(str(path))
    if image.shape != (IMAGE_SIZE, IMAGE_SIZE):
        raise ValueError(f"Expected {IMAGE_SIZE}x{IMAGE_SIZE}, got {image.shape}: {path}")
    if image.dtype != np.uint8:
        raise ValueError(f"Expected uint8, got {image.dtype}: {path}")
    return image


def meaningful_improvement(current, reference, rel_threshold):
    """Check the original relative improvement threshold."""
    if not np.isfinite(reference):
        return True
    return current < reference * (1.0 - rel_threshold)


def format_duration(seconds):
    """Format a measured elapsed time for the training report."""
    seconds = max(0.0, float(seconds))
    rounded = int(round(seconds))
    hours, remainder = divmod(rounded, 3600)
    minutes, secs = divmod(remainder, 60)
    if hours > 0:
        return f"{hours}h {minutes:02d}m {secs:02d}s"
    if minutes > 0:
        return f"{minutes}m {secs:02d}s"
    return f"{seconds:.1f}s"


